import { writeFileSync } from 'node:fs'

/**
 * Bundle the Express app into plain JS for Vercel's Node runtime.
 * @vercel/node only reliably compiles the api entry; relative .ts imports
 * otherwise survive into /var/task and crash Node with ERR_MODULE_NOT_FOUND.
 *
 * Vercel locks in `api/index.ts` as the function entrypoint from the
 * uploaded source tree *before* installCommand runs, so this script must
 * rewrite that file in place rather than delete/replace it — deleting it
 * makes the later build step fail with "File not found: api/index.ts".
 */
const result = await Bun.build({
  entrypoints: ['app.ts'],
  target: 'node',
  format: 'esm',
  packages: 'external',
})

if (!result.success) {
  for (const log of result.logs) console.error(log)
  throw new Error('Bun.build failed for app.ts')
}

await Bun.write('api/app.bundle.mjs', await result.outputs[0].text())

writeFileSync(
  'api/index.ts',
  [
    '// Generated by scripts/build-vercel-api.mjs — do not edit by hand.',
    "import app from './app.bundle.mjs'",
    'export default app',
    '',
  ].join('\n'),
)

console.log('Built Vercel API entry: api/index.ts (-> app.bundle.mjs)')
